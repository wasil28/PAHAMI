/** Ganti `{kunci}` di teks dengan nilai. */
export function isi(teks: string, nilai: Record<string, string | number>): string {
  return teks.replace(/\{(\w+)\}/g, (_, k: string) => String(nilai[k] ?? `{${k}}`));
}
